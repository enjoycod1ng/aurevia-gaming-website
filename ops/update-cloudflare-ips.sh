#!/usr/bin/env bash
set -Eeuo pipefail

# Writes the Nginx http-level include that restores visitor IPs only from
# Cloudflare and marks which connections came through Cloudflare. Run it on the
# VPS as root to refresh the live copy (it tests and reloads Nginx), or with a
# path to refresh the checked-in reference copy:
#
#   sudo bash ops/update-cloudflare-ips.sh
#   bash ops/update-cloudflare-ips.sh ops/nginx-cloudflare.conf

TARGET="${1:-/etc/nginx/conf.d/aurevia-cloudflare.conf}"
CIDR_V4='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$'
CIDR_V6='^[0-9a-f:]+::?[0-9a-f:]*/[0-9]{1,3}$'

fetch() {
  curl --fail --silent --show-error --max-time 20 "$1"
}

mapfile -t ipv4 < <(fetch https://www.cloudflare.com/ips-v4 | tr -d '\r' | sed '/^$/d')
mapfile -t ipv6 < <(fetch https://www.cloudflare.com/ips-v6 | tr -d '\r' | sed '/^$/d')

# An empty or malformed list would either block all visitors or trust everyone.
if (( ${#ipv4[@]} < 5 || ${#ipv6[@]} < 3 )); then
  echo "Cloudflare returned too few ranges; refusing to write $TARGET." >&2
  exit 1
fi
for range in "${ipv4[@]}"; do
  [[ "$range" =~ $CIDR_V4 ]] || { echo "Unexpected IPv4 range: $range" >&2; exit 1; }
done
for range in "${ipv6[@]}"; do
  [[ "$range" =~ $CIDR_V6 ]] || { echo "Unexpected IPv6 range: $range" >&2; exit 1; }
done

WORK_DIR="$(mktemp -d)"
TEMP="$WORK_DIR/aurevia-cloudflare.conf"
BACKUP="$WORK_DIR/previous.conf"
RESTORE_ON_EXIT=false

# Until Nginx accepts the new include, an exit (including a failed test) puts
# the previous one back, or removes the new one if there was none.
cleanup() {
  if [[ "$RESTORE_ON_EXIT" == "true" ]]; then
    if [[ -f "$BACKUP" ]]; then
      install -m 0644 "$BACKUP" "$TARGET"
      echo "Restored the previous $TARGET; Nginx was not reloaded." >&2
    else
      rm -f -- "$TARGET"
      echo "Removed the new $TARGET; Nginx was not reloaded." >&2
    fi
  fi
  rm -rf -- "$WORK_DIR"
}
trap cleanup EXIT

{
  echo "# Generated by ops/update-cloudflare-ips.sh on $(date -u +%Y-%m-%d) from"
  echo "# https://www.cloudflare.com/ips-v4 and https://www.cloudflare.com/ips-v6."
  echo "# Install in the http context (/etc/nginx/conf.d/). Do not edit by hand."
  echo
  echo "# \$remote_addr becomes CF-Connecting-IP only for connections from Cloudflare."
  echo "real_ip_header CF-Connecting-IP;"
  for range in "${ipv4[@]}" "${ipv6[@]}"; do
    echo "set_real_ip_from $range;"
  done
  echo
  echo "# 1 when the TCP peer is Cloudflare (or this host); site configs refuse the rest."
  echo "geo \$realip_remote_addr \$aurevia_from_cloudflare {"
  echo "    default 0;"
  echo "    127.0.0.1 1;"
  echo "    ::1 1;"
  for range in "${ipv4[@]}" "${ipv6[@]}"; do
    echo "    $range 1;"
  done
  echo "}"
} > "$TEMP"

if [[ "$TARGET" != /etc/nginx/* ]]; then
  install -m 0644 "$TEMP" "$TARGET"
  echo "Wrote $TARGET (${#ipv4[@]} IPv4 and ${#ipv6[@]} IPv6 ranges)."
  exit 0
fi

if [[ -f "$TARGET" ]]; then
  cp -p -- "$TARGET" "$BACKUP"
fi

RESTORE_ON_EXIT=true
install -m 0644 "$TEMP" "$TARGET"
echo "Wrote $TARGET (${#ipv4[@]} IPv4 and ${#ipv6[@]} IPv6 ranges)."

if ! nginx -t; then
  echo "nginx -t rejected the new ranges." >&2
  exit 1
fi

RESTORE_ON_EXIT=false
systemctl reload nginx
echo "Nginx reloaded."
